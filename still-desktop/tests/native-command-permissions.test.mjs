import {test} from 'node:test';
import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';

const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const handler=read('../src-tauri/src/main.rs').match(/generate_handler!\[([\s\S]*?)\]\)/)?.[1]??'';
const commandList=read('../src-tauri/build.rs').match(/\.commands\(&\[([\s\S]*?)\]\)/)?.[1]??'';
const capability=JSON.parse(read('../src-tauri/capabilities/main.json'));
const commands=[...handler.matchAll(/\b\w+::(\w+)\b/g)].map(match=>match[1]);
const buildCommands=[...commandList.matchAll(/"([a-z0-9_]+)"/g)].map(match=>match[1]);
const permissions=new Set(capability.permissions);

test('every native command is generated and granted to Still’s local UI',()=>{
 assert.ok(commands.length>0,'the Tauri command handler is discoverable');
 for(const command of commands){
  const permission=command.replaceAll('_','-');
  assert.ok(buildCommands.includes(command),`${command} is missing from the generated permission manifest`);
  assert.ok(existsSync(new URL(`../src-tauri/permissions/autogenerated/${command}.toml`,import.meta.url)),`${command} has no generated permission`);
  assert.ok(permissions.has(`allow-${permission}`),`${command} is registered but not allowed by the main capability`);
 }
});
